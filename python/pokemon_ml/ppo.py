"""PPO for self-play: collecting games, working out advantages, and the update.

Collection supports current self-play and episode-stable frozen/scripted
opponents. Only actions generated by the learner enter PPO updates. The only reward is the
result: 1 to the winner and -1 to the loser when a game ends, nothing before,
nothing discounted.
"""

from dataclasses import dataclass

import time
import torch

from .features import History, HISTORY_F, HISTORY_I
from . import auxiliary
from .env import OBS_F, OBS_I, N_ACTIONS, part


@dataclass
class Config:
    steps: int = 64  # decisions every game advances between two updates
    epochs: int = 2  # passes over what was collected
    minibatch: int = 4096
    lr: float = 3e-4
    clip: float = 0.2  # how far one update may move the policy
    lam: float = 0.95  # generalized advantage estimation
    value_coef: float = 0.5
    entropy_coef: float = 0.01
    # Jaxcalibur's "zero-avoiding" term: a pull towards the uniform policy that keeps every
    # legal action from dying out (the cross-entropy from uniform to the policy).
    uniform_coef: float = 0.001
    max_grad_norm: float = 0.5
    opponent_coef: float = 0.05
    hidden_coef: float = 0.05

    def __post_init__(self):
        if min(self.steps, self.epochs) < 1 or self.minibatch < 2 or self.lr <= 0:
            raise ValueError("PPO counts and learning rate must be positive")
        if not 0 < self.clip < 1 or not 0 <= self.lam <= 1:
            raise ValueError("clip must be in (0,1), lambda in [0,1]")
        if (
            self.max_grad_norm <= 0
            or min(
                self.value_coef,
                self.entropy_coef,
                self.uniform_coef,
                self.opponent_coef,
                self.hidden_coef,
            )
            < 0
        ):
            raise ValueError(
                "gradient limit must be positive and loss coefficients nonnegative"
            )


class Rollout:
    """What `steps` decisions of `batch` observations need remembering, on `device`."""

    def __init__(self, steps, batch, device, history=0, auxiliary_labels=False):
        z = lambda *shape, dtype=torch.float32: torch.zeros(
            steps, batch, *shape, dtype=dtype, device=device
        )
        self.f, self.i = z(OBS_F), z(OBS_I, dtype=torch.int16)
        self.mask0, self.mask1 = (
            z(N_ACTIONS, dtype=torch.bool),
            z(N_ACTIONS, dtype=torch.bool),
        )
        self.actions = z(2, dtype=torch.long)
        self.logp, self.value, self.reward = z(), z(), z()
        self.valid, self.done = z(dtype=torch.bool), z(dtype=torch.bool)
        self.last_value = torch.zeros(batch, device=device)
        self.steps, self.batch, self.device = steps, batch, device
        self.history = History(batch, history, device)
        self.hf, self.hi, self.hvalid = (
            z(history, HISTORY_F),
            z(history, HISTORY_I, dtype=torch.long),
            z(history, dtype=torch.bool),
        )
        self.opponent, self.opponent_valid, self.private = (
            (z(2, dtype=torch.long), z(dtype=torch.bool), z(6, 8, dtype=torch.long))
            if auxiliary_labels
            else (None, None, None)
        )
        self.timings = {}
        self.phase = z(dtype=torch.long)
        self.legal = z()


def to_device(env, device):
    """The environment's current observations as tensors."""
    return (
        torch.from_numpy(env.f).to(device),
        torch.from_numpy(env.i).to(device),
        torch.from_numpy(env.mask).to(device),
    )


@torch.no_grad()
def collect(env, model, roll, league=None):
    """Collect on-policy learner rows; opponents remain fixed until episode end."""
    model.eval()
    clock = lambda: (
        torch.cuda.synchronize(roll.device)
        if str(roll.device).startswith("cuda")
        else None,
        time.perf_counter(),
    )[1]
    timings = dict(
        transfer_seconds=0.0,
        inference_seconds=0.0,
        simulation_seconds=0.0,
        scripted_opponent_seconds=0.0,
    )
    for t in range(roll.steps):
        begin = clock()
        f, i, mask = to_device(env, roll.device)
        timings["transfer_seconds"] += clock() - begin
        hist = roll.history.tensors()
        if model.config.history:
            roll.hf[t], roll.hi[t], roll.hvalid[t] = hist
        begin = clock()
        actions, logp, value, mask0, mask1 = model.act(
            f, i, mask, history=hist if model.config.history else None
        )
        learner = (
            league.replace_actions(env, f, i, mask, actions, hist)
            if league is not None
            else torch.ones(len(f), dtype=torch.bool, device=f.device)
        )
        scripted = league.scripted_seconds if league is not None else 0.0
        timings["inference_seconds"] += clock() - begin - scripted
        timings["scripted_opponent_seconds"] += scripted
        roll.f[t], roll.i[t] = f, i
        roll.mask0[t], roll.mask1[t] = mask0.bool(), mask1.bool()
        roll.actions[t], roll.logp[t], roll.value[t] = actions, logp, value
        info = part(i, "i", "info")
        roll.valid[t] = (info[:, 3] == 1) & learner
        roll.phase[t], roll.legal[t] = info[:, 0], info[:, 1].float()
        if roll.opponent is not None:
            roll.opponent[t], roll.opponent_valid[t], roll.private[t] = (
                auxiliary.labels(i, actions)
            )
        roll.history.append(f, i, info[:, 3] == 1)
        begin = clock()
        host_actions = actions.cpu().numpy()
        timings["transfer_seconds"] += clock() - begin
        begin = clock()
        env.step(host_actions)
        timings["simulation_seconds"] += clock() - begin
        begin = clock()
        roll.reward[t] = torch.from_numpy(env.reward).to(roll.device).reshape(-1)
        over = torch.from_numpy(env.done).to(roll.device).bool().repeat_interleave(2)
        roll.done[t] = over
        roll.history.reset(over)
        if league is not None:
            league.assign(env.done.astype(bool))
        timings["transfer_seconds"] += clock() - begin
    f, i, _ = to_device(env, roll.device)
    field = model.encode(
        f, i, roll.history.tensors() if model.config.history else None
    )[0]
    roll.last_value = model.value(field)
    roll.timings = timings


def advantages(value, reward, done, valid, last_value, lam):
    """Generalized advantage estimates and the returns to fit the value to, without
    discounting. All [steps, batch]; `done[t]` says the game ended on the action of step `t`
    (so what follows is another game), `valid[t]` that the side had a decision to make.
    A result that arrives on a step where a side had no decision goes to its last one."""
    adv = torch.zeros_like(value)
    next_value, next_adv, pending = (
        last_value.clone(),
        torch.zeros_like(last_value),
        torch.zeros_like(last_value),
    )
    for t in reversed(range(value.shape[0])):
        over = done[t]
        next_value = next_value.masked_fill(over, 0.0)
        next_adv = next_adv.masked_fill(over, 0.0)
        pending = pending.masked_fill(over, 0.0) + reward[t]
        a = pending + next_value - value[t] + lam * next_adv
        here = valid[t]
        adv[t] = torch.where(here, a, torch.zeros_like(a))
        next_value = torch.where(here, value[t], next_value)
        next_adv = torch.where(here, a, next_adv)
        pending = pending.masked_fill(here, 0.0)
    return adv, adv + value


def update(model, optimizer, roll, config):
    """One PPO update on a rollout. Returns what happened, for the log."""
    adv, returns = advantages(
        roll.value, roll.reward, roll.done, roll.valid, roll.last_value, config.lam
    )
    flat = lambda x: x.reshape(roll.steps * roll.batch, *x.shape[2:])
    f, i, mask0, mask1 = flat(roll.f), flat(roll.i), flat(roll.mask0), flat(roll.mask1)
    actions, old_logp, old_value, adv, returns = (
        flat(roll.actions),
        flat(roll.logp),
        flat(roll.value),
        flat(adv),
        flat(returns),
    )
    rows = flat(roll.valid).nonzero().squeeze(1)
    model.eval()  # Gradients remain enabled; dropout must match collection likelihoods.
    log = {
        k: 0.0
        for k in (
            "policy_loss",
            "value_loss",
            "entropy",
            "kl",
            "clipped",
            "grad_norm",
            "opponent_loss",
            "hidden_loss",
        )
    }
    for phase in range(3):
        log[f"entropy_phase_{phase}"] = 0.0
        log[f"normalized_entropy_phase_{phase}"] = 0.0
    phase_counts = [0, 0, 0]
    auxiliary_metrics = {}
    auxiliary_counts = {}
    history = (
        tuple(flat(x) for x in (roll.hf, roll.hi, roll.hvalid))
        if model.config.history
        else None
    )
    phases, legal = flat(roll.phase), flat(roll.legal)
    if len(rows) < 2:
        raise ValueError(
            "rollout requires at least two learner decisions; increase envs or steps"
        )
    deferred = getattr(getattr(model, "runtime", None), "deferred_metrics", False)
    # Accumulate detached scalar tensors on device and transfer once per update.
    scalar = (lambda x: x.detach()) if deferred else (lambda x: float(x))
    batches = 0
    for _ in range(config.epochs):
        order = rows[torch.randperm(len(rows), device=rows.device)]
        for start in range(0, len(order), config.minibatch):
            mb = order[start : start + config.minibatch]
            if len(mb) < 2:
                continue
            hist = None if history is None else tuple(x[mb] for x in history)
            logp, entropy, spread, value, outputs = model.evaluate(
                f[mb],
                i[mb],
                mask0[mb],
                mask1[mb],
                actions[mb],
                history=hist,
                return_aux=True,
            )
            aux = {"opponent_loss": value.sum() * 0, "hidden_loss": value.sum() * 0}
            if model.config.opponent_prediction or model.config.hidden_prediction:
                if roll.opponent is None:
                    raise ValueError("auxiliary experiments require rollout labels")
                aux = auxiliary.loss(
                    outputs,
                    i[mb],
                    flat(roll.opponent)[mb],
                    flat(roll.opponent_valid)[mb],
                    flat(roll.private)[mb],
                    f[mb],
                )
                for key, val in auxiliary.metrics(
                    outputs,
                    i[mb],
                    flat(roll.opponent)[mb],
                    flat(roll.opponent_valid)[mb],
                    flat(roll.private)[mb],
                    f[mb],
                ).items():
                    auxiliary_metrics[key] = auxiliary_metrics.get(key, 0.0) + val
                    auxiliary_counts[key] = auxiliary_counts.get(key, 0) + 1
            a = adv[mb]
            a = (a - a.mean()) / (a.std() + 1e-8)
            ratio = (logp - old_logp[mb]).exp()
            policy_loss = -torch.min(
                ratio * a, ratio.clamp(1 - config.clip, 1 + config.clip) * a
            ).mean()
            value_loss = 0.5 * (value - returns[mb]).pow(2).mean()
            loss = (
                policy_loss
                + config.value_coef * value_loss
                - config.entropy_coef * entropy.mean()
                - config.uniform_coef * spread.mean()
                + config.opponent_coef * aux["opponent_loss"]
                + config.hidden_coef * aux["hidden_loss"]
            )
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            grad_norm = torch.nn.utils.clip_grad_norm_(
                model.parameters(), config.max_grad_norm
            )
            optimizer.step()
            with torch.no_grad():
                log["policy_loss"] += scalar(policy_loss)
                log["value_loss"] += scalar(value_loss)
                log["entropy"] += scalar(entropy.mean())
                log["kl"] += scalar(
                    (ratio - 1 - (logp - old_logp[mb])).clamp_min(0).mean()
                )
                log["grad_norm"] += scalar(grad_norm)
                for key, val in aux.items():
                    log[key] += scalar(val)
                for phase in range(3):
                    chosen = phases[mb] == phase
                    phase_counts[phase] += scalar(chosen.sum())
                    log[f"entropy_phase_{phase}"] += scalar(entropy[chosen].sum())
                    # Legal joint count is an upper bound on joint entropy.
                    normal = entropy / legal[mb].clamp(min=2).log()
                    log[f"normalized_entropy_phase_{phase}"] += scalar(
                        normal[chosen].sum()
                    )
                log["clipped"] += scalar(
                    ((ratio - 1).abs() > config.clip).float().mean()
                )
            batches += 1
    log = {
        k: v
        / (
            (
                phase_counts[int(k[-1])].clamp_min(1)
                if torch.is_tensor(phase_counts[int(k[-1])])
                else max(phase_counts[int(k[-1])], 1)
            )
            if "entropy_phase_" in k
            else max(batches, 1)
        )
        for k, v in log.items()
    }
    # How much of the spread in results the value explained when the games were played.
    spread_of = returns[rows].var()
    log["explained"] = (
        (1 - (returns[rows] - old_value[rows]).var() / spread_of).item()
        if spread_of > 0
        else 0.0
    )
    log["decisions"] = len(rows)
    log.update(roll.timings)
    log.update({k: v / auxiliary_counts[k] for k, v in auxiliary_metrics.items()})
    tensors = {k: v for k, v in log.items() if torch.is_tensor(v)}
    if tensors:
        values = torch.stack([v.float() for v in tensors.values()]).cpu().tolist()
        log.update(zip(tensors, values))
    return log


@torch.no_grad()
def play_baseline(env, model, kind, games, device, greedy=False):
    from .evaluation import play

    report = play(env, model, kind, games, device, greedy=greedy)
    return report["score"]
